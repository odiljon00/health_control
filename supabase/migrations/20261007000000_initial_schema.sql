create or replace function public.is_active_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid()) and p.role = 'admin' and p.is_active
  );
$$;

create or replace function public.can_access_school(target_school_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_active_admin()
    or (
      public.current_school_id() = target_school_id
      and public.current_profile_role() in ('teacher', 'psychologist', 'school_admin', 'iio')
    );
$$;

create or replace function public.can_manage_school(target_school_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_active_admin()
    or (
      public.current_school_id() = target_school_id
      and public.current_profile_role() in ('teacher', 'psychologist', 'school_admin')
    );
$$;

create or replace function public.can_access_risk_case(target_case_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_active_admin()
    or exists (
      select 1 from public.risk_cases c
      where c.id = target_case_id
        and (
          public.can_access_school(c.school_id)
          or (
            c.notify_parent
            and exists (
              select 1 from public.students s
              where s.id = c.student_id and s.parent_id = (select auth.uid())
            )
          )
        )
    );
$$;

create or replace function public.protect_profile_access()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is not null
    and not public.is_active_admin()
    and (
      new.role is distinct from old.role
      or new.school_id is distinct from old.school_id
      or new.is_active is distinct from old.is_active
    )
  then
    raise exception 'Only an administrator can change profile access fields';
  end if;
  return new;
end;
$$;

create trigger profiles_protect_access
before update on public.profiles
for each row execute function public.protect_profile_access();

create or replace function public.validate_student_parent()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.parent_id is not null and not exists (
    select 1 from public.profiles p
    where p.id = new.parent_id
      and p.role = 'parent'
      and p.is_active
      and p.school_id = new.school_id
  ) then
    raise exception 'The parent must be an active parent at the student school';
  end if;
  return new;
end;
$$;

create trigger students_validate_parent
before insert or update on public.students
for each row execute function public.validate_student_parent();

create or replace function public.protect_record_tenant()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is not null and not public.is_active_admin() then
    if tg_table_name = 'students' and (
      new.school_id is distinct from old.school_id
      or new.parent_id is distinct from old.parent_id
    ) then
      raise exception 'Only an administrator can reassign a student';
    elsif tg_table_name = 'attendances' and (
      new.school_id is distinct from old.school_id
      or new.student_id is distinct from old.student_id
      or (
        new.marked_by is distinct from old.marked_by
        and new.marked_by is distinct from (select auth.uid())
      )
    ) then
      raise exception 'Attendance ownership cannot be changed';
    elsif tg_table_name = 'risk_cases' and (
      new.school_id is distinct from old.school_id
      or new.student_id is distinct from old.student_id
      or new.reported_by is distinct from old.reported_by
    ) then
      raise exception 'Risk case ownership cannot be changed';
    elsif tg_table_name = 'case_actions' and (
      new.risk_case_id is distinct from old.risk_case_id
      or new.user_id is distinct from old.user_id
    ) then
      raise exception 'Case action ownership cannot be changed';
    end if;
  end if;
  return new;
end;
$$;

create trigger students_protect_tenant before update on public.students
for each row execute function public.protect_record_tenant();
create trigger attendances_protect_tenant before update on public.attendances
for each row execute function public.protect_record_tenant();
create trigger risk_cases_protect_tenant before update on public.risk_cases
for each row execute function public.protect_record_tenant();

create or replace function public.sync_risk_level()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.risk_level = case
    when new.risk_score >= 70 then 'red'
    when new.risk_score >= 40 then 'yellow'
    else 'green'
  end;
  return new;
end;
$$;

create trigger risk_cases_sync_level
before insert or update of risk_score, risk_level on public.risk_cases
for each row execute function public.sync_risk_level();

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name, email, role, is_active)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'name', ''),
    coalesce(new.email, ''),
    'parent',
    true
  );
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

