create table public.schools (
  id bigint generated by default as identity primary key,
  name text not null,
  region text,
  district text,
  address text,
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '',
  email text not null default '',
  role text not null default 'parent'
    check (role in ('admin', 'teacher', 'psychologist', 'school_admin', 'parent', 'iio')),
  school_id bigint references public.schools (id) on delete set null,
  phone text,
  avatar text,
  position text,
  is_active boolean not null default true,
  notify_email boolean not null default true,
  notify_sms boolean not null default true,
  notify_risk_cases boolean not null default true,
  notify_attendance boolean not null default true,
  language text not null default 'uz',
  timezone text not null default 'Asia/Tashkent',
  theme text not null default 'light' check (theme in ('light', 'dark')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.students (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  middle_name text,
  birth_date date,
  class_name text not null,
  school_id bigint not null references public.schools (id) on delete cascade,
  parent_id uuid references public.profiles (id) on delete set null,
  gender text check (gender in ('male', 'female')),
  photo text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint students_id_school_unique unique (id, school_id)
);

create table public.attendances (
  id bigint generated by default as identity primary key,
  student_id bigint not null,
  school_id bigint not null references public.schools (id) on delete cascade,
  marked_by uuid not null references public.profiles (id) on delete restrict,
  attendance_date date not null default current_date,
  status text not null default 'present'
    check (status in ('present', 'absent', 'late', 'excused')),
  is_excused boolean not null default false,
  reason text,
  note text,
  is_alert boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendances_student_date_unique unique (student_id, attendance_date),
  constraint attendances_student_school_fkey
    foreign key (student_id, school_id) references public.students (id, school_id) on delete cascade
);

create table public.risk_cases (
  id bigint generated by default as identity primary key,
  student_id bigint not null,
  reported_by uuid not null references public.profiles (id) on delete restrict,
  school_id bigint not null references public.schools (id) on delete cascade,
  risk_type text not null,
  risk_score integer not null default 0 check (risk_score between 0 and 100),
  risk_level text not null default 'green' check (risk_level in ('red', 'yellow', 'green')),
  description text,
  status text not null default 'new'
    check (status in ('new', 'in_progress', 'improved', 'ongoing', 'severe', 'closed')),
  psychologist_id uuid references public.profiles (id) on delete set null,
  psychologist_note text,
  notify_parent boolean not null default true,
  notify_iio boolean not null default false,
  notified_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint risk_cases_student_school_fkey
    foreign key (student_id, school_id) references public.students (id, school_id) on delete cascade
);

create table public.case_actions (
  id bigint generated by default as identity primary key,
  risk_case_id bigint not null references public.risk_cases (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete restrict,
  action_type text not null,
  note text,
  result text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  subject text,
  message text not null,
  status text not null default 'new' check (status in ('new', 'read', 'replied', 'archived')),
  is_starred boolean not null default false,
  admin_note text,
  read_at timestamptz,
  replied_at timestamptz,
  ip_address text,
  user_agent text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create view public.parent_visible_risk_cases
with (security_barrier = true)
as
select
  c.id,
  c.student_id,
  c.risk_type,
  c.risk_score,
  c.risk_level,
  c.description,
  c.status,
  c.created_at,
  c.updated_at,
  s.first_name,
  s.last_name,
  s.middle_name,
  s.class_name
from public.risk_cases c
join public.students s on s.id = c.student_id
where c.notify_parent
  and s.parent_id = (select auth.uid());

